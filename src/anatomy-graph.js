/**
 * Returns tooth graph record by FDI or Universal identifier.
 * @param {number|string} id
 */
export function getToothData(id) {
  const num = parseInt(id, 10);
  if (TOOTH_CLINICAL_GRAPH[num]) return TOOTH_CLINICAL_GRAPH[num];
  // check universal
  for (const t of Object.values(TOOTH_CLINICAL_GRAPH)) {
    if (t.universal === num) return t;
  }
  return null;
}

